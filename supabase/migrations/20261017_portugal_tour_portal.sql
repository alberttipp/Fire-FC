-- PORTUGAL TOUR PORTAL (Rockford Raptors — São Miguel, Azores, April 2027).
-- Public, branded trip HQ at /portugal?club=rockford-raptors: parents commit a
-- player (hard commit by Nov 15) or raise a hand as "interested", families are
-- counted for travel planning, and staff get a live admin panel (stats, roster,
-- deposit tracking). Mirrors the winter portal architecture: RLS on with NO
-- table policies — all access flows through SECURITY DEFINER RPCs below.

create table if not exists public.portugal_signups (
    id                  uuid primary key default gen_random_uuid(),
    org_id              uuid not null references public.organizations(id),
    trip_key            text not null default 'sao-miguel-2027',
    age_group           text not null,                        -- 'U11' | 'U12'
    player_first_name   text not null,
    player_last_name    text not null,
    contact_name        text,
    contact_relation    text,                                 -- Mom/Dad/Guardian/...
    contact_email       text,
    contact_phone       text,
    commitment          text not null default 'committed',    -- 'committed' | 'interested'
    family_parents      int  not null default 0,
    family_siblings     int  not null default 0,
    family_other        int  not null default 0,
    ack_player_deposit  boolean not null default false,
    ack_family_deposit  boolean not null default false,
    notes               text,
    source              text,                                 -- ?src= attribution
    status              text not null default 'new',          -- new | confirmed | waitlist | withdrawn
    deposit_paid        boolean not null default false,
    deposit_paid_at     timestamptz,
    admin_notes         text,
    created_at          timestamptz not null default now()
);
alter table public.portugal_signups enable row level security;  -- RPC access only
create index if not exists portugal_signups_org_idx on public.portugal_signups(org_id, trip_key);

create table if not exists public.portugal_visits (
    id         bigint generated by default as identity primary key,
    org_id     uuid not null references public.organizations(id),
    visit_id   text,
    source     text,
    created_at timestamptz not null default now()
);
alter table public.portugal_visits enable row level security;  -- RPC access only
create index if not exists portugal_visits_org_idx on public.portugal_visits(org_id, created_at);

-- PUBLIC: live spot counts for the tracker ("7 of 12 U11 spots claimed").
-- Counts only — never names or contact info.
create or replace function public.portugal_public_stats(p_org_slug text)
returns json language sql stable security definer set search_path = public as $$
    select json_build_object(
        'u11_committed', (select count(*) from public.portugal_signups ps
                           join public.organizations o on o.id = ps.org_id
                          where o.slug = p_org_slug and ps.age_group = 'U11'
                            and ps.commitment = 'committed' and ps.status <> 'withdrawn'),
        'u12_committed', (select count(*) from public.portugal_signups ps
                           join public.organizations o on o.id = ps.org_id
                          where o.slug = p_org_slug and ps.age_group = 'U12'
                            and ps.commitment = 'committed' and ps.status <> 'withdrawn'),
        'interested',    (select count(*) from public.portugal_signups ps
                           join public.organizations o on o.id = ps.org_id
                          where o.slug = p_org_slug and ps.commitment = 'interested'
                            and ps.status <> 'withdrawn')
    );
$$;

-- PUBLIC (anon): commit a player / register interest. Dedupes on the same kid
-- in the same org+trip (double-tap safe); a repeat submit UPGRADES an earlier
-- "interested" row to "committed" and refreshes contact info rather than
-- duplicating. Notifies org managers/directors in-app on each new commit.
create or replace function public.submit_portugal_signup(
    p_org_slug text,
    p_age_group text,
    p_player_first text,
    p_player_last text,
    p_contact_name text,
    p_contact_relation text,
    p_email text,
    p_phone text,
    p_commitment text default 'committed',
    p_family_parents int default 0,
    p_family_siblings int default 0,
    p_family_other int default 0,
    p_ack_player boolean default false,
    p_ack_family boolean default false,
    p_notes text default null,
    p_source text default null
) returns json language plpgsql security definer set search_path = public as $$
declare
    v_org uuid; v_id uuid; v_staff uuid;
    v_commit text := case when p_commitment = 'interested' then 'interested' else 'committed' end;
begin
    select id into v_org from public.organizations where slug = p_org_slug and deleted_at is null;
    if v_org is null then
        return json_build_object('success', false, 'message', 'Unknown club.');
    end if;
    if p_age_group not in ('U11', 'U12') then
        return json_build_object('success', false, 'message', 'Please pick U11 or U12.');
    end if;
    if coalesce(trim(p_player_first), '') = '' or coalesce(trim(p_player_last), '') = '' then
        return json_build_object('success', false, 'message', 'Player first and last name are required.');
    end if;
    if coalesce(trim(p_contact_name), '') = '' or coalesce(trim(p_email), '') = '' then
        return json_build_object('success', false, 'message', 'Your name and email are required.');
    end if;

    -- dedupe: same kid, same org/trip → update rather than duplicate
    select id into v_id from public.portugal_signups
    where org_id = v_org and trip_key = 'sao-miguel-2027'
      and lower(trim(player_first_name)) = lower(trim(p_player_first))
      and lower(trim(player_last_name))  = lower(trim(p_player_last))
    limit 1;
    if v_id is not null then
        update public.portugal_signups set
            commitment         = case when commitment = 'committed' then 'committed' else v_commit end,
            age_group          = p_age_group,
            contact_name       = coalesce(nullif(trim(p_contact_name), ''), contact_name),
            contact_relation   = coalesce(nullif(trim(p_contact_relation), ''), contact_relation),
            contact_email      = coalesce(nullif(trim(p_email), ''), contact_email),
            contact_phone      = coalesce(nullif(trim(p_phone), ''), contact_phone),
            family_parents     = greatest(0, least(10, coalesce(p_family_parents, 0))),
            family_siblings    = greatest(0, least(10, coalesce(p_family_siblings, 0))),
            family_other       = greatest(0, least(10, coalesce(p_family_other, 0))),
            ack_player_deposit = ack_player_deposit or coalesce(p_ack_player, false),
            ack_family_deposit = ack_family_deposit or coalesce(p_ack_family, false),
            notes              = coalesce(nullif(left(trim(p_notes), 2000), ''), notes)
        where id = v_id;
        return json_build_object('success', true, 'id', v_id, 'duplicate', true);
    end if;

    insert into public.portugal_signups(
        org_id, age_group, player_first_name, player_last_name,
        contact_name, contact_relation, contact_email, contact_phone,
        commitment, family_parents, family_siblings, family_other,
        ack_player_deposit, ack_family_deposit, notes, source)
    values (
        v_org, p_age_group, trim(p_player_first), trim(p_player_last),
        trim(p_contact_name), nullif(trim(p_contact_relation), ''),
        trim(p_email), nullif(trim(p_phone), ''),
        v_commit,
        greatest(0, least(10, coalesce(p_family_parents, 0))),
        greatest(0, least(10, coalesce(p_family_siblings, 0))),
        greatest(0, least(10, coalesce(p_family_other, 0))),
        coalesce(p_ack_player, false), coalesce(p_ack_family, false),
        nullif(left(trim(p_notes), 2000), ''), nullif(trim(p_source), ''))
    returning id into v_id;

    -- in-app ping to org leadership (managers + directors) so momentum is visible
    for v_staff in
        select distinct tm.user_id
        from public.team_memberships tm join public.teams t on t.id = tm.team_id
        where t.org_id = v_org and tm.role in ('manager', 'team_manager', 'club_director')
    loop
        perform public.enqueue_notification(
            v_staff, 'portugal_signup',
            case when v_commit = 'committed' then '🇵🇹 Portugal: new commit!' else '🇵🇹 Portugal: new interest' end,
            trim(p_player_first) || ' ' || trim(p_player_last) || ' (' || p_age_group || ') — ' || v_commit,
            '/portugal?club=' || p_org_slug, 'portugal_signup_' || v_id::text, v_org);
    end loop;

    return json_build_object('success', true, 'id', v_id);
end;
$$;

-- ANON: log a page open, deduped to one row per visit_id per day (Central).
create or replace function public.log_portugal_visit(p_org_slug text, p_visit_id text, p_source text default null)
returns void language plpgsql security definer set search_path = public as $$
declare v_org uuid;
begin
    select id into v_org from public.organizations where slug = p_org_slug and deleted_at is null;
    if v_org is null then return; end if;
    if p_visit_id is not null and exists(
        select 1 from public.portugal_visits v
        where v.org_id = v_org and v.visit_id = p_visit_id
          and (v.created_at at time zone 'America/Chicago')::date = (now() at time zone 'America/Chicago')::date
    ) then return; end if;
    insert into public.portugal_visits(org_id, visit_id, source)
    values (v_org, p_visit_id, nullif(trim(p_source), ''));
end;
$$;

-- Staff check for this portal (wrapper over the shared org-staff helper).
create or replace function public.am_i_portugal_staff(p_org_slug text)
returns boolean language sql stable security definer set search_path = public as $$
    select coalesce((
        select public._rc_is_org_staff(o.id)
        from public.organizations o where o.slug = p_org_slug
    ), false);
$$;

-- STAFF: headline stats + opens-by-day/source.
create or replace function public.portugal_stats_admin(p_org_slug text)
returns json language plpgsql stable security definer set search_path = public as $$
declare v_org uuid; v_res json;
begin
    select id into v_org from public.organizations where slug = p_org_slug;
    if v_org is null or not public._rc_is_org_staff(v_org) then raise exception 'not authorized'; end if;
    select json_build_object(
        'opens_total',     (select count(*) from public.portugal_visits where org_id = v_org),
        'unique_visitors', (select count(distinct visit_id) from public.portugal_visits where org_id = v_org),
        'committed',       (select count(*) from public.portugal_signups where org_id = v_org and commitment = 'committed' and status <> 'withdrawn'),
        'interested',      (select count(*) from public.portugal_signups where org_id = v_org and commitment = 'interested' and status <> 'withdrawn'),
        'deposits_paid',   (select count(*) from public.portugal_signups where org_id = v_org and deposit_paid),
        'family_travelers',(select coalesce(sum(family_parents + family_siblings + family_other), 0)
                              from public.portugal_signups where org_id = v_org and commitment = 'committed' and status <> 'withdrawn'),
        'opens_by_day',    (select coalesce(json_agg(row_to_json(d) order by d.day), '[]') from (
                               select to_char((created_at at time zone 'America/Chicago')::date, 'MM-DD') as day, count(*) as opens
                               from public.portugal_visits where org_id = v_org and created_at > now() - interval '14 days'
                               group by 1) d),
        'opens_by_source', (select coalesce(json_agg(row_to_json(s) order by s.visitors desc), '[]') from (
                               select coalesce(source, 'direct / other') as source, count(distinct visit_id) as visitors
                               from public.portugal_visits where org_id = v_org
                               group by 1) s)
    ) into v_res;
    return v_res;
end;
$$;

-- STAFF: the full organizer roster — every field, for the admin panel + CSV.
create or replace function public.list_portugal_signups_admin(p_org_slug text)
returns table(
    id uuid, age_group text, player_first text, player_last text,
    contact_name text, contact_relation text, contact_email text, contact_phone text,
    commitment text, family_parents int, family_siblings int, family_other int,
    ack_player_deposit boolean, ack_family_deposit boolean, notes text,
    status text, deposit_paid boolean, deposit_paid_at timestamptz,
    admin_notes text, source text, created_at timestamptz)
language plpgsql stable security definer set search_path = public as $$
declare v_org uuid;
begin
    select o.id into v_org from public.organizations o where o.slug = p_org_slug;
    if v_org is null or not public._rc_is_org_staff(v_org) then raise exception 'not authorized'; end if;
    return query
        select ps.id, ps.age_group, ps.player_first_name, ps.player_last_name,
               ps.contact_name, ps.contact_relation, ps.contact_email, ps.contact_phone,
               ps.commitment, ps.family_parents, ps.family_siblings, ps.family_other,
               ps.ack_player_deposit, ps.ack_family_deposit, ps.notes,
               ps.status, ps.deposit_paid, ps.deposit_paid_at,
               ps.admin_notes, ps.source, ps.created_at
        from public.portugal_signups ps
        where ps.org_id = v_org
        order by (ps.commitment = 'committed') desc, ps.age_group, ps.created_at;
end;
$$;

-- STAFF: update a signup (deposit toggle, status, private notes). NULL params
-- leave the field unchanged.
create or replace function public.update_portugal_signup_admin(
    p_signup_id uuid,
    p_status text default null,
    p_deposit_paid boolean default null,
    p_admin_notes text default null
) returns json language plpgsql security definer set search_path = public as $$
declare v_org uuid;
begin
    select org_id into v_org from public.portugal_signups where id = p_signup_id;
    if v_org is null then return json_build_object('success', false, 'message', 'Signup not found.'); end if;
    if not public._rc_is_org_staff(v_org) then raise exception 'not authorized'; end if;
    if p_status is not null and p_status not in ('new', 'confirmed', 'waitlist', 'withdrawn') then
        return json_build_object('success', false, 'message', 'Bad status.');
    end if;
    update public.portugal_signups set
        status          = coalesce(p_status, status),
        deposit_paid    = coalesce(p_deposit_paid, deposit_paid),
        deposit_paid_at = case when p_deposit_paid is true  then coalesce(deposit_paid_at, now())
                               when p_deposit_paid is false then null
                               else deposit_paid_at end,
        admin_notes     = coalesce(nullif(left(trim(p_admin_notes), 2000), ''), admin_notes)
    where id = p_signup_id;
    return json_build_object('success', true);
end;
$$;

